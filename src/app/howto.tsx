// あそびかたのカード。その端末で初めて遊ぶモードには「はじめて」の印を付ける
export function HowTo({ mode, compact }: { mode: GameMode; compact?: boolean }) {
  const h = HOWTO[mode];
  const first = !loadPlayed().includes(mode);
  return (
    <div className={`howto ${compact ? 'compact' : ''}`}>
      <div className="howto-head"><span className="howto-icon" aria-hidden>{h.icon}</span><b>{h.lead}</b>{first && !compact && <span className="howto-new">🔰 はじめて</span>}</div>
      <ol>{h.steps.map((s, i) => <li key={i}>{s}</li>)}</ol>
    </div>
  );
}
