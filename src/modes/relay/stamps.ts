// 置いたスタンプ1つ：k = STAMPS の番号、x・y = 位置（0〜100）、s = 大きさ（1〜5）、r = 向き（0〜7。45度きざみ）
export interface Stamp { k: number; x: number; y: number; s: number; r: number }

// 届いた絵を検査して整える（形のおかしいものは捨てる）
export function sanitizeStamps(raw: unknown): Stamp[] {
  if (!Array.isArray(raw)) return [];
  const int = (v: unknown, min: number, max: number) => Math.max(min, Math.min(max, Math.round(Number(v) || 0)));
  return raw.filter(s => s && typeof s === 'object' && Number.isInteger(s.k) && s.k >= 0 && s.k < STAMPS.length).slice(0, RELAY_MAX_STAMPS)
    .map(s => ({ k: s.k, x: int(s.x, 0, 100), y: int(s.y, 0, 100), s: int(s.s, 1, RELAY_SIZES), r: int(s.r, 0, 7) }));
}
export const cleanAnswer = (raw: unknown) => String(raw ?? '').replace(/\s+/g, ' ').trim().slice(0, RELAY_TEXT_MAX);
// 「合っているか」を比べるための形（空白を取り、カタカナをひらがなに、英字を小文字に）
export const normalizeAnswer = (w: string) => w.replace(/\s+/g, '').toLowerCase().replace(/[ァ-ヶ]/g, c => String.fromCharCode(c.charCodeAt(0) - 0x60));

