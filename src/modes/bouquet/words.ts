// 手札：名詞6・言い回し5・修飾3 の14枚（文になりやすいよう、種類を混ぜて配る）
const HAND = { nouns: 6, phrases: 5, mods: 3 };
export const HAND_SIZE = HAND.nouns + HAND.phrases + HAND.mods;
export function dealHand(random: Random): string[] {
  return [...shuffle(NOUNS, random).slice(0, HAND.nouns), ...shuffle(PHRASES, random).slice(0, HAND.phrases), ...shuffle(MODS, random).slice(0, HAND.mods)];
}

// 助詞など：手札と別に、何度でも使える（助詞が足りずに文にならない、という不満を防ぐ）
export const PARTICLES = ['は', 'が', 'を', 'に', 'の', 'と', 'で', 'も', 'へ', 'から', 'より', 'まで', 'や', 'か', 'ね', 'よ', 'な', 'って', '、', '！', '？', '…'] as const;
export const PHRASE_MAX = 12; // 1つの文に並べられる数（カードと助詞を合わせて）

// 並べたもの：0以上 = 手札の番号、負の数 = 助詞（-1 が PARTICLES[0]）
export const particleToken = (i: number) => -(i + 1);
// 並べたものが正しい形か（手札は1枚1回まで・少なくとも1枚は手札を使う）。正しければ、つないだ文を返す
export function toPhrase(tokens: unknown, hand: readonly string[]): string | null {
  if (!Array.isArray(tokens) || tokens.length < 1 || tokens.length > PHRASE_MAX || !tokens.every(Number.isInteger)) return null;
  const used = new Set<number>();
  const parts: string[] = [];
  for (const t of tokens as number[]) {
    if (t >= 0) {
      if (t >= hand.length || used.has(t)) return null;
      used.add(t);
      parts.push(hand[t]);
    } else {
      const p = PARTICLES[-t - 1];
      if (p == null) return null;
      parts.push(p);
    }
  }
  return used.size ? parts.join('') : null;
}

// ===== お題 =====
export function sanitizeBouquets(list: unknown): string[] {
  if (!Array.isArray(list)) return [];
  return [...new Set(list.slice(0, MAX_TOPICS_PER_PLAYER).map(t => clean(t, TITLE_MAX)).filter(Boolean))];
}
